package org.javaRoad.lesson030_regex.task1;

public class Main {
    /**
     * Реализуйте boolean-метод, валидирующий входящую строку. Метод должен возвращать true, если строка соответствует
     * номеру мобильного телефона (в качестве примера привожу номер для РФ, вы можете выбрать любой другой, но со
     * схожей маской).
     * Маска корректного номера: +7 (XXX) XXX-XX-XX, где X – цифра от 0 до 9. Обратите внимание на наличие скобок
     * и пробелов.
     * Вариант с усложнением (*): решите ту же задачу, но символы скобок, дефиса и пробелов – опциональны (каждый из
     * них может или присутствовать, как на оригинальной маске, так и отсутствовать вовсе, возможность
     * частичного использования или использования символов-разделителей в другом порядке считаем невалидным).
     */

    private static final String REGEX = "^\\+7 ?(\\(\\d{3}\\)|\\d{3}) ?\\d{3}-?\\d{2}-?\\d{2}$";

    public static void main(String[] args) {
        String[] phoneNumber = {
                "abc+7(910)5514436d",
                "+7 (910) 551-44-36",
                "+7(910)5514436",
                "+79105514436",
                "+7(910)))5514436",
                "+7(910 5514436",
                "+7(910)55144?36"};

        for (String s : phoneNumber) {
            System.out.println(s + " " + isPhoneNumberValid(s));
        }

    }

    private static boolean isPhoneNumberValid(String number) {
        return number.matches(REGEX);
    }
}
